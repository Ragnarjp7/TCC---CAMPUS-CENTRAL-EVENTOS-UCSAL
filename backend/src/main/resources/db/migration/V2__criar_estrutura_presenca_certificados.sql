CREATE TABLE IF NOT EXISTS codigos_presenca (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL,
    token VARCHAR(128) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_codigo_presenca_evento UNIQUE (evento_id),
    CONSTRAINT uk_codigo_presenca_token UNIQUE (token),

    CONSTRAINT fk_codigo_presenca_evento
        FOREIGN KEY (evento_id)
        REFERENCES eventos (id)
);

CREATE TABLE IF NOT EXISTS presencas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL,
    inscricao_id BIGINT,
    usuario_id BIGINT,
    nome_participante_externo VARCHAR(150),
    email_participante_externo VARCHAR(150),
    data_confirmacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_presenca_evento
        FOREIGN KEY (evento_id)
        REFERENCES eventos (id),

    CONSTRAINT fk_presenca_inscricao
        FOREIGN KEY (inscricao_id)
        REFERENCES inscricoes (id),

    CONSTRAINT fk_presenca_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id)
);

CREATE TABLE IF NOT EXISTS certificados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presenca_id BIGINT NOT NULL,
    nome_participante VARCHAR(150) NOT NULL,
    email_destinatario VARCHAR(150) NOT NULL,
    data_geracao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    arquivo_pdf BYTEA NOT NULL,
    email_enviado BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT uk_certificado_presenca UNIQUE (presenca_id),

    CONSTRAINT fk_certificado_presenca
        FOREIGN KEY (presenca_id)
        REFERENCES presencas (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_presenca_evento_inscricao
    ON presencas (evento_id, inscricao_id);

CREATE UNIQUE INDEX IF NOT EXISTS uk_presenca_evento_usuario
    ON presencas (evento_id, usuario_id);

CREATE UNIQUE INDEX IF NOT EXISTS uk_presenca_evento_email_externo
    ON presencas (evento_id, email_participante_externo);

CREATE INDEX IF NOT EXISTS idx_presencas_evento
    ON presencas (evento_id);

CREATE INDEX IF NOT EXISTS idx_certificados_evento
    ON certificados (presenca_id);